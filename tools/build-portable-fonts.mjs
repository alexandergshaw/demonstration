import { readFile, writeFile } from 'node:fs/promises';

// Regenerate after changing the self-hosted fonts. Exports keep their bytes and license offline.
const license = await readFile(new URL('../public/fonts/IBM-Plex-OFL.txt', import.meta.url), 'utf8');
const faces = await Promise.all([
  ['Regular', 400],
  ['SemiBold', 600],
].map(async ([name, weight]) => {
  const bytes = await readFile(new URL(`../public/fonts/IBMPlexSans-${name}.woff2`, import.meta.url));
  return `@font-face{font-family:'IBM Plex Sans';font-style:normal;font-weight:${weight};font-display:swap;src:url('data:font/woff2;base64,${bytes.toString('base64')}') format('woff2')}`;
}));
const output = new URL('../src/portable-font-faces.css', import.meta.url);
const content = `/* Generated by tools/build-portable-fonts.mjs from public/fonts.\n${license.replaceAll('*/', '* /')}\n*/\n${faces.join('\n')}\n`;
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')).replaceAll('\r\n', '\n') !== content.replaceAll('\r\n', '\n')) {
    throw new Error('Portable fonts differ from the app fonts. Run node tools/build-portable-fonts.mjs.');
  }
} else {
  await writeFile(output, content);
}
